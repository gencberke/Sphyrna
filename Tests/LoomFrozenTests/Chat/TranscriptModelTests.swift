/// The same model fed from transcript lines: a turn ends at the next human prompt, rows keep the ids the live stream
/// gives them, and records Claude writes for other purposes are not mistaken for prompts.
@Suite(.timeLimit(.minutes(1)))
struct TranscriptModelTests: TranscriptModelFixtures {
    @Test func turnsEndAtTheNextHumanPromptAndNotAtOtherUserRecords() {
        let model = build([
            Fixture.line(["type": "summary", "summary": "x", "leafUuid": "l"]),
            Fixture.line(["type": "file-history-snapshot", "messageId": "m", "snapshot": [:]]),
            Fixture.transcriptUser("fix the bug", uuid: "p1"),
            Fixture.transcriptUser("Caveat: the messages below were generated by the user running local commands", uuid: "meta1", extra: ["isMeta": true]),
            Fixture.transcriptAssistant(messageID: "msg_a", uuid: "a1", blocks: [Fixture.thinkingBlock("**Reading** the code")], time: "2026-10-17T10:00:05.000Z"),
            Fixture.transcriptAssistant(messageID: "msg_a", uuid: "a2", blocks: [Fixture.toolUse("toolu_1", "Bash", ["command": "ls"])], time: "2026-10-17T10:00:06.000Z"),
            Fixture.transcriptToolResult(id: "toolu_1", text: "a.py", time: "2026-10-17T10:00:07.000Z", structured: ["stdout": "a.py"]),
            Fixture.transcriptAssistant(messageID: "msg_b", uuid: "a3", blocks: [Fixture.textBlock("Done.")], time: "2026-10-17T10:00:10.000Z"),
            Fixture.transcriptUser("<command-name>/review</command-name>\n<command-message>review</command-message>\n<command-args>src</command-args>", uuid: "p2", time: "2026-10-17T10:05:00.000Z"),
            Fixture.transcriptUser("[Request interrupted by user]", uuid: "int1", time: "2026-10-17T10:05:30.000Z"),
            Fixture.line(["type": "future-record", "uuid": "f1", "data": 1]),
            Fixture.transcriptUser("<local-command-stdout>Context: 12%</local-command-stdout>", uuid: "out1", time: "2026-10-17T10:05:40.000Z"),
            Fixture.transcriptUser("and now the tests", uuid: "p3", time: "2026-10-17T10:06:00.000Z"),
            Fixture.transcriptAssistant(messageID: "msg_c", uuid: "a4", blocks: [Fixture.textBlock("Sure.")], time: "2026-10-17T10:06:04.000Z"),
        ])
        #expect(model.prompts.map(\.text) == ["fix the bug", "/review src", "and now the tests"])
        #expect(model.prompts[1].command == UserPrompt.Command(name: "/review", arguments: "src"))
        #expect(model.turns.count == 3 && model.turns.allSatisfy(\.hasUserPrompt))
        #expect(model.turns.map(\.status) == [.ended, .interrupted, .open])
        // The first turn lasted from its prompt to its last record: 10 s.
        #expect(abs((model.turns[0].durationMs ?? 0) - 10_000) < 1)
        #expect(model.markers == [.interrupted(afterMs: nil), .notice("Context: 12%")])
        // Unknown records stay raw; the quiet ones leave no row.
        #expect(model.raws.count == 1 && model.raws[0].type == "future-record" && model.unknownRecordCount == 1)
        #expect(model.entries.filter { $0.turnID == model.turns[0].id }.count == 4)
        // The tool call and its result are one row; the thinking block kept its place.
        #expect(model.tools.count == 1 && model.tools[0].output?.text == "a.py" && model.tools[0].status == .succeeded)
        #expect(model.thoughtLine(in: model.turns[0]) == "Reading")
        // Rows carry where they came from, for "Show all".
        #expect(model.entry(id: "p1")?.sourceOffset != nil)
    }

    @Test func rowIdsMatchWhatTheLiveStreamGives() {
        let transcript = build([
            Fixture.transcriptUser("go", uuid: "u1"),
            Fixture.transcriptAssistant(messageID: "msg_1", uuid: "a1", blocks: [Fixture.thinkingBlock("hm")]),
            Fixture.transcriptAssistant(messageID: "msg_1", uuid: "a2", blocks: [Fixture.textBlock("I'll look.")]),
            Fixture.transcriptAssistant(messageID: "msg_1", uuid: "a3", blocks: [Fixture.toolUse("toolu_1", "Bash", ["command": "ls"])]),
        ])
        var live = TurnModel(source: .live)
        live.appendPendingUser(uuid: "u1", text: "go")
        for line in [Fixture.assistant(messageID: "msg_1", uuid: "x1", blocks: [Fixture.thinkingBlock("hm")]),
                     Fixture.assistant(messageID: "msg_1", uuid: "x2", blocks: [Fixture.textBlock("I'll look.")]),
                     Fixture.assistant(messageID: "msg_1", uuid: "x3", blocks: [Fixture.toolUse("toolu_1", "Bash", ["command": "ls"])])] {
            live.apply(Fixture.message(line))
        }
        #expect(transcript.entries.map(\.id) == live.entries.map(\.id))
        #expect(transcript.entries.map(\.id) == ["u1", "msg_1#0", "msg_1#1", "toolu_1"])
    }

    @Test func aSubagentTranscriptIsOneThreadWithItsBriefFirst() {
        let model = build([
            Fixture.transcriptUser("Review auth.py for bugs", uuid: "b1", extra: ["isSidechain": true]),
            Fixture.transcriptAssistant(messageID: "s1", uuid: "s1a", blocks: [Fixture.toolUse("st1", "Read", ["file_path": "auth.py"])]),
            Fixture.transcriptToolResult(id: "st1", text: "def login(): ..."),
            Fixture.transcriptAssistant(messageID: "s2", uuid: "s2a", blocks: [Fixture.textBlock("No bugs found.")]),
        ], source: .subagentTranscript)
        #expect(model.prompts.count == 1 && model.prompts[0].isBrief && model.turns.count == 1)
        #expect(model.entries.allSatisfy { $0.thread == .main })
        #expect(model.tools[0].status == .succeeded && model.texts.map(\.text) == ["No bugs found."])
    }

    @Test func aSessionTranscriptKeepsSidechainRecordsOutOfTheMainThread() {
        let model = build([
            Fixture.transcriptUser("go", uuid: "u1"),
            Fixture.transcriptUser("sub prompt", uuid: "sp", extra: ["isSidechain": true]),
            Fixture.transcriptAssistant(messageID: "s1", uuid: "sa", blocks: [Fixture.textBlock("sub work")]),
        ].enumerated().map { index, line in
            index == 2 ? line.replacingOccurrences(of: #""isSidechain":false"#, with: #""isSidechain":true"#) : line
        })
        #expect(model.prompts.count == 1 && model.turns.count == 1)
        #expect(model.entries.last?.thread == .subagent("sidechain"))
    }

    @Test func aLineThatWasNotReadOrIsNotJSONIsStillARow() {
        var model = TurnModel(source: .sessionTranscript)
        model.apply(record: TranscriptLineRecord(offset: 100, length: 9_000_000, bytes: nil))
        let junk = Data("{not json".utf8)
        model.apply(record: TranscriptLineRecord(offset: 9_000_101, length: junk.count, bytes: junk))
        #expect(model.raws.map(\.reason) == [.oversized, .malformed])
        #expect(model.raws[0].byteCount == 9_000_000 && model.entries[0].sourceOffset == 100)
        #expect(model.entries[1].sourceOffset == 9_000_101)
    }

    @Test func longToolOutputKeepsItsHeadAndTail() {
        let body = "HEAD" + String(repeating: "m", count: 300_000) + "TAIL"
        let model = build([
            Fixture.transcriptUser("cat it", uuid: "u1"),
            Fixture.transcriptAssistant(messageID: "m1", uuid: "a1", blocks: [Fixture.toolUse("t1", "Bash", ["command": "cat big", "pad": .string(String(repeating: "p", count: 100_000))])]),
            Fixture.transcriptToolResult(id: "t1", text: body),
        ])
        let output = model.tools[0].output
        #expect(output?.isClipped == true && output?.totalBytes == body.utf8.count)
        #expect(output?.head.hasPrefix("HEAD") == true && output?.tail.hasSuffix("TAIL") == true)
        #expect((output?.head.utf8.count ?? 0) + (output?.tail.utf8.count ?? 0) <= ClippedText.budgetBytes)
        // The call's own long strings are cut too.
        #expect(model.tools[0].input["pad"]?.string?.utf8.count ?? 0 < 70_000)
    }

    @Test func prependingAnOlderReadKeepsTheRowsAndJoinsACutTurn() {
        let all = [
            Fixture.transcriptUser("one", uuid: "p1"),
            Fixture.transcriptAssistant(messageID: "m1", uuid: "a1", blocks: [Fixture.textBlock("first answer")]),
            Fixture.transcriptUser("two", uuid: "p2"),
            Fixture.transcriptAssistant(messageID: "m2", uuid: "a2", blocks: [Fixture.toolUse("t2", "Bash", ["command": "ls"])]),
            Fixture.transcriptToolResult(id: "t2", text: "x"),
            Fixture.transcriptAssistant(messageID: "m3", uuid: "a3", blocks: [Fixture.textBlock("second answer")]),
        ]
        let whole = build(all)
        // Read newest first: the last three records, which cut turn two in the middle, then the rest.
        var newer = TurnModel(source: .sessionTranscript)
        for line in all[3...] {
            let bytes = Data(line.utf8)
            newer.apply(record: TranscriptLineRecord(offset: 0, length: bytes.count, bytes: bytes))
        }
        #expect(newer.turns.count == 1 && !newer.turns[0].hasUserPrompt)
        let older = build(Array(all[..<3]))
        newer.prepend(older)
        #expect(newer.entries.map(\.id) == whole.entries.map(\.id))
        #expect(newer.turns.map(\.id) == whole.turns.map(\.id) && newer.turns.map(\.hasUserPrompt) == [true, true])
        #expect(newer.turns.map(\.status) == [.ended, .open])
        #expect(newer.entries.map(\.turnID) == whole.entries.map(\.turnID))
    }

    @Test func prependingAReadThatBeginsWithAToolResultTakesTheCallInAndKeepsIdsUnique() {
        let all = [
            Fixture.transcriptUser("one", uuid: "p1"),
            Fixture.transcriptAssistant(messageID: "m1", uuid: "a1", blocks: [Fixture.textBlock("first answer")]),
            Fixture.transcriptUser("two", uuid: "p2"),
            Fixture.transcriptAssistant(messageID: "m2", uuid: "a2", blocks: [Fixture.toolUse("t2", "Bash", ["command": "ls"])]),
            Fixture.transcriptToolResult(id: "t2", text: "x", structured: ["stdout": "x"]),
            Fixture.transcriptAssistant(messageID: "m3", uuid: "a3", blocks: [Fixture.textBlock("second answer")]),
        ]
        let whole = build(all)
        // The newer read cuts between the call and its result, so it starts with the result alone.
        var newer = build(Array(all[4...]))
        #expect(newer.tools.count == 1 && newer.tools[0].name.isEmpty && newer.tools[0].status == .succeeded)
        newer.prepend(build(Array(all[..<4])))
        let ids = newer.entries.map(\.id)
        #expect(Set(ids).count == ids.count && ids == whole.entries.map(\.id))
        #expect(newer.tools.count == 1 && newer.tools[0].name == "Bash" && newer.tools[0].status == .succeeded)
        #expect(newer.tools[0].output?.text == "x" && newer.tools[0].input["command"] == "ls")
        #expect(newer.turns.map(\.id) == whole.turns.map(\.id) && newer.turns.map(\.status) == [.ended, .open])
        #expect(newer.entries.map(\.turnID) == whole.entries.map(\.turnID))
        // Dividers that opened the newer read, before any turn, join the turn the older read ended in.
        var withDivider = build([Fixture.line(["type": "future-record", "uuid": "f1"])] + Array(all[3...]))
        #expect(withDivider.entries.first?.turnID == "")
        withDivider.prepend(build(Array(all[..<3])))
        #expect(withDivider.entries.allSatisfy { !$0.turnID.isEmpty })
    }

    @Test func aBackgroundAgentEndsWithItsNotificationEvenWhenTheCallLiesInAnOlderRead() {
        let lines = S2Transcript.backgroundAgent
        let running = build(Array(lines[..<2]))
        #expect(running.entries.first?.id.hasPrefix("toolu_") == true)
        if case let .subagent(run) = running.entries.first(where: { if case .subagent = $0.body { true } else { false } })?.body {
            #expect(run.status == .running)
        } else {
            Issue.record("the Agent call should be a subagent row")
        }
        func agentStatus(_ model: TurnModel) -> SubagentRun.Status? {
            for entry in model.entries { if case let .subagent(run) = entry.body { return run.status } }
            return nil
        }
        #expect(agentStatus(running) == .running)
        #expect(agentStatus(build(lines)) == .succeeded)
        // The notification arrives in a newer read; the call is in the older one.
        var newer = build([lines[2]])
        #expect(newer.entries.map(\.id).count == 1) // the notice
        newer.prepend(build(Array(lines[..<2])))
        #expect(agentStatus(newer) == .succeeded)
        #expect(newer.entries.map(\.id).count == Set(newer.entries.map(\.id)).count)
    }

    @Test func localCommandAndApiErrorSystemRecordsOfTheTranscriptAreTyped() {
        let model = build([
            Fixture.transcriptUser("hi", uuid: "p1"),
            Fixture.line(["type": "system", "subtype": "local_command", "uuid": "s1",
                          "content": "<command-name>/model</command-name>\n <command-message>model</command-message>\n <command-args></command-args>"]),
            Fixture.line(["type": "system", "subtype": "local_command", "uuid": "s2",
                          "content": "<local-command-stdout>Kept model as `Haiku 4.5`</local-command-stdout>"]),
            Fixture.line(["type": "system", "subtype": "local_command", "uuid": "s3", "content": "<local-command-stdout></local-command-stdout>"]),
            Fixture.line(["type": "system", "subtype": "api_error", "uuid": "s4", "retryAttempt": 1, "maxRetries": 10,
                          "error": ["message": "Connection error."]]),
            Fixture.line(["type": "system", "subtype": "stop_hook_summary", "uuid": "s5"]),
        ])
        #expect(model.markers == [.notice("Kept model as `Haiku 4.5`"), .retry(attempt: 1, maxRetries: 10, error: "Connection error.")])
        #expect(model.raws.isEmpty)
    }

    @Test func anInterruptNoticeKeepsTheSameRowWhereverTheReadBegan() {
        let lines = [
            Fixture.transcriptUser("go", uuid: "p1"),
            Fixture.transcriptAssistant(messageID: "m1", uuid: "a1", blocks: [Fixture.toolUse("t1", "Bash", ["command": "sleep 9"])]),
            Fixture.transcriptUser("[Request interrupted by user for tool use]", uuid: "int1"),
        ]
        let whole = build(lines)
        #expect(whole.markers == [.interrupted(afterMs: nil)] && whole.turns.map(\.status) == [.interrupted])
        // A read that starts at the notice still shows it, under the same id.
        let fragment = build([lines[2]])
        #expect(fragment.markers == [.interrupted(afterMs: nil)] && fragment.entries.map(\.id) == whole.entries.suffix(1).map(\.id))
    }

    @Test func anEmptyFileCreatedByWriteAddsNoLines() {
        func added(_ content: String) -> Int? {
            TurnModel.lineChanges(from: ["type": "create", "content": .string(content)])?.added
        }
        #expect(added("") == 0 && added("one") == 1 && added("one\n") == 1 && added("a\nb\n") == 2 && added("a\nb") == 2 && added("\n") == 1)
    }
